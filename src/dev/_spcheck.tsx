import "@/index.css";
import { createRoot } from "react-dom/client";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { StartPriceCandidatesCard } from "@/fakturaer/components/StartPriceCandidatesCard";
const row = { invoice_line_id: "L1", raw_material_name: "Hvetemel", description: "x", supplier_name: "S", invoice_number: "1", invoice_date: "2026-01-01", price_per_base_unit: 10, currency: "NOK" };
const qc = new QueryClient({ defaultOptions: { queries: { retry: false, staleTime: Infinity } } });
qc.setQueryDefaults(["x"], {});
const orig = qc.getQueryCache().build.bind(qc.getQueryCache());
qc.getQueryCache().build = ((c: never, o: { queryKey: unknown[] }) => { const q = orig(c, o); if (q.state.data === undefined) q.setData([row]); return q; }) as never;
createRoot(document.getElementById("r")!).render(<QueryClientProvider client={qc}><div className="p-4"><StartPriceCandidatesCard legalEntityId="LE" canWrite /></div></QueryClientProvider>);
